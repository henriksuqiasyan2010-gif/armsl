"""Глобальные настройки проекта: пути, параметры камеры, гиперпараметры модели.

Здесь и только здесь живут все константы проекта. В остальных файлах
никаких «магических чисел» — импортируем отсюда.
"""

from pathlib import Path

# --- Пути ------------------------------------------------------------------

# Корень проекта (папка armsl/) вычисляется от расположения этого файла,
# поэтому пути работают одинаково, откуда бы ни запускали скрипт.
PROJECT_ROOT = Path(__file__).resolve().parent.parent

MODELS_DIR = PROJECT_ROOT / "models"
DATA_DIR = PROJECT_ROOT / "data"
RAW_DATA_DIR = DATA_DIR / "raw"
REPORTS_DIR = PROJECT_ROOT / "reports"

# Справочник меток жестов (label_id -> армянское написание/произношение/значение).
LABELS_CSV_PATH = DATA_DIR / "labels.csv"

# Метаданные всех записанных сэмплов — одна строка на сэмпл, дописывается
# при каждой новой записи (см. src/dataset.py: record_sample).
META_CSV_PATH = DATA_DIR / "meta.csv"

# Порядок колонок в meta.csv — фиксирован, чтобы запись и чтение всегда
# совпадали. Строка нужна и как заголовок файла, и как fieldnames для csv.DictWriter.
META_CSV_COLUMNS = [
    "file", "label", "person", "session",
    "date", "lighting", "background", "distance_m", "notes",
]

# Файл модели детекции рук MediaPipe Tasks.
# Лежит локально, в git не хранится (см. .gitignore), скачивается вручную
# один раз. Во время работы программы ничего не скачиваем.
HAND_LANDMARKER_MODEL_PATH = MODELS_DIR / "hand_landmarker.task"

# --- Параметры детекции рук ------------------------------------------------

# Обе руки: часть жестов армянского жестового языка двуручные.
NUM_HANDS = 2

# Число ключевых точек на одной руке в модели MediaPipe Hand Landmarker.
# Это свойство самой модели, а не наш выбор.
NUM_LANDMARKS = 21

# Пороги уверенности.
# ВАЖНО: это ДЕФОЛТНЫЕ значения из документации MediaPipe Tasks API
# (HandLandmarkerOptions), а не подобранные нами числа. Вынесены сюда явно,
# чтобы потом было видно, что именно можно крутить, если детекция шумит.
MIN_HAND_DETECTION_CONFIDENCE = 0.5   # дефолт MediaPipe: min_hand_detection_confidence
MIN_HAND_PRESENCE_CONFIDENCE = 0.5    # дефолт MediaPipe: min_hand_presence_confidence
MIN_TRACKING_CONFIDENCE = 0.5         # дефолт MediaPipe: min_tracking_confidence

# --- Формат признаков (см. контракт данных в CLAUDE.md) -------------------

# Размер вектора одного кадра: 2 руки x 21 точка x (x, y, z) + 2 флага видимости.
HAND_VECTOR_SIZE = NUM_LANDMARKS * 3          # 63
FEATURE_VECTOR_SIZE = 2 * HAND_VECTOR_SIZE + 2  # 128

# Число кадров в одном окне жеста (см. контракт данных в CLAUDE.md).
WINDOW_LENGTH = 60

# Индекс запястья в 21 точке руки — точка, относительно которой убираем
# смещение (позицию человека в кадре).
WRIST_LANDMARK_INDEX = 0

# Индекс точки, по которой оцениваем размер ладони (масштаб) — MCP-сустав
# среднего пальца. Выбран потому, что почти не двигается при сгибании
# пальцев (в отличие, например, от кончика пальца), а значит даёт более
# стабильную оценку масштаба руки от кадра к кадру.
PALM_SIZE_LANDMARK_INDEX = 9

# Нижняя граница масштаба руки при нормализации: если оценка масштаба
# случайно оказалась около нуля (вырожденный кадр), делим не на неё,
# а на этот порог — чтобы не получить деление на ноль/NaN/inf.
NORMALIZATION_EPSILON = 1e-6

# --- Аугментация сырых окон (см. src/dataset.py: augment) -----------------

# Стандартное отклонение гауссова шума, добавляемого к координатам (x,y,z).
# Величина в тех же единицах, что и сами landmark-координаты (0..1 для x,y).
# Небольшая, чтобы не превратить настоящий жест в другой.
AUGMENT_NOISE_STD = 0.01

# Максимальный случайный сдвиг всего окна по каждой оси (x,y,z), в тех же
# единицах, что координаты. Одно и то же смещение на все 60 кадров сразу.
AUGMENT_SHIFT_RANGE = 0.02

# Диапазон случайного множителя масштаба (один на всё окно). 0.9..1.1 —
# рука "то же самое", просто чуть ближе/дальше от камеры.
AUGMENT_SCALE_RANGE = (0.9, 1.1)

# --- Обучение (см. src/train.py) -------------------------------------------

# Общий сид по умолчанию для RandomForest/numpy/random/keras — воспроизводимость (NFR-4).
RANDOM_SEED = 42

# Baseline: RandomForestClassifier на расплющенном окне (60*128=7680 признаков).
RF_N_ESTIMATORS = 200

# GRU: Masking -> GRU -> Dropout -> GRU -> Dense -> Dense(softmax).
GRU_UNITS_1 = 64
GRU_UNITS_2 = 32
GRU_DROPOUT = 0.3
DENSE_UNITS = 32
GRU_LEARNING_RATE = 1e-3
GRU_EPOCHS = 100          # верхний предел; EarlyStopping почти всегда остановит раньше
GRU_BATCH_SIZE = 16       # маленький датасет на раннем этапе — маленький батч
GRU_PATIENCE = 10         # EarlyStopping(monitor="val_loss", patience=...)

# Куда сохраняется обученная GRU-модель и снимок списка классов — ВСЕГДА
# вместе, одной операцией (см. src/train.py: save_model_with_labels_snapshot).
# .classes.json — это снимок ДЛЯ ПРОВЕРКИ, а не второй редактируемый список
# (единственный источник истины по классам — data/labels.csv, см. CLAUDE.md).
GRU_MODEL_PATH = MODELS_DIR / "gesture_gru.keras"
GRU_CLASSES_SNAPSHOT_PATH = MODELS_DIR / "gesture_gru.classes.json"

# --- Отчёты об обучении (см. src/train.py) ---------------------------------

EXPERIMENTS_CSV_PATH = REPORTS_DIR / "experiments.csv"

# Порядок колонок в experiments.csv — фиксирован по тем же причинам, что
# и META_CSV_COLUMNS в dataset.py: строка нужна и как заголовок, и как
# fieldnames для csv.DictWriter при дозаписи.
EXPERIMENTS_CSV_COLUMNS = [
    "run_id", "timestamp", "model",
    "augment_noise", "augment_shift", "augment_scale",
    "n_train", "n_val", "n_classes", "val_groups",
    "accuracy", "macro_f1", "per_class_f1",
]

# --- Инференс в реальном времени (см. src/predictor.py) --------------------

# Инференс не на каждый кадр, а раз в PREDICT_STRIDE кадров.
# Сама сеть крошечная (~3M MAC на окно), платим за накладные расходы вызова
# модели — единицы-десятки мс на CPU. При 30 FPS бюджет кадра 33 мс, и
# MediaPipe на две руки уже съедает заметную его часть.
# Цена шага — задержка, и она умножается на сглаживание:
#   5 кадров ожидания шага (~0.17 с) + SMOOTHING_WINDOW инференсов по 5
#   кадров (~0.83 с) ≈ до ~1 с от конца жеста до засчитанного слова.
# Шаг 3 дал бы ~0.6 с ценой вдвое большей нагрузки, шаг 10 — под 2 с.
PREDICT_STRIDE = 5

# Ниже этого порога предсказание не засчитывается как слово, но занимает
# слот в истории сглаживания как "неуверенное" (и тем самым мешает набрать
# нужное число голосов — так и задумано).
# При 15 классах случайное угадывание даёт 0.067. Значение стартовое:
# на малых данных softmax обычно переуверен, уточним по reports/.
CONFIDENCE_THRESHOLD = 0.7

# Сглаживание: голосование по последним SMOOTHING_WINDOW инференсам
# (не кадрам!), слово засчитывается при SMOOTHING_MIN_VOTES совпадениях.
SMOOTHING_WINDOW = 5
SMOOTHING_MIN_VOTES = 4

# Пауза после засчитанного слова. Отсчитывается по реальному времени
# (time.monotonic), а не по числу кадров — иначе зависела бы от FPS камеры.
COOLDOWN_SECONDS = 1.0

# Сколько гипотез отдавать наружу для отображения в GUI ("как думает модель").
TOP_K_PREDICTIONS = 3

# Метка "класса покоя" (человек не жестикулирует). ЗАГОТОВКА: такой метки
# в data/labels.csv пока нет — она появится при реальной съёмке, дописанная
# В КОНЕЦ файла (правило append-only, иначе индексы softmax съедут), после
# чего модель переобучается.
# В predictor.py никакой особой логики для неё нет и не будет: класс покоя
# просто побеждает голосование, когда человек не жестикулирует. Фильтровать
# его при показе/добавлении в предложение — задача app.py, ему и нужна
# эта константа.
REST_LABEL_ID = None
